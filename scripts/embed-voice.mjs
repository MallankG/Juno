// Embeds the files in voice/ into agent/lib/voice-assets.ts so the agent
// serves the phone app itself (one deployment, one origin, no CORS).
// Run automatically by `npm run dev` and `npm run build`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const dir = new URL("../voice/", import.meta.url).pathname;
const types = {
  ".html": "text/html; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".js": "text/javascript; charset=utf-8",
  ".png": "image/png",
};

const entries = [];
for (const file of readdirSync(dir)) {
  const ext = extname(file);
  if (!types[ext]) continue;
  const name = file === "index.html" ? "/" : `/${file}`;
  const binary = ext === ".png";
  const body = binary ? readFileSync(join(dir, file)).toString("base64") : readFileSync(join(dir, file), "utf8");
  entries.push(`  ${JSON.stringify(name)}: { type: ${JSON.stringify(types[ext])}, binary: ${binary}, body: ${JSON.stringify(body)} },`);
}

const out = `// Generated by scripts/embed-voice.mjs from voice/. Do not edit by hand.
export const voiceAssets: Record<string, { type: string; binary: boolean; body: string }> = {
${entries.join("\n")}
};
`;
writeFileSync(new URL("../agent/lib/voice-assets.ts", import.meta.url), out);
console.log(`embedded ${entries.length} voice assets`);
