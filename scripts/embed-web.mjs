// Embeds the built phone app (web/dist, made by `npm run build:web`) into
// agent/lib/web-assets.ts so the agent serves it itself: one deployment,
// one origin, no CORS. Run by `npm run dev` and `npm run build`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const dir = new URL("../web/dist/", import.meta.url).pathname;
if (!existsSync(join(dir, "index.html"))) {
  console.error("web/dist is missing. Run `npm run build:web` first.");
  process.exit(1);
}

const types = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
};
const binaryTypes = new Set([".png"]);

const files = [];
const walk = (d) => {
  for (const name of readdirSync(d)) {
    const full = join(d, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
};
walk(dir);

const entries = [];
for (const full of files.sort()) {
  const ext = extname(full);
  if (!types[ext]) continue;
  const rel = relative(dir, full).split("\\").join("/");
  const name = rel === "index.html" ? "/" : `/${rel}`;
  const binary = binaryTypes.has(ext);
  const body = binary ? readFileSync(full).toString("base64") : readFileSync(full, "utf8");
  // Hashed bundles never change, so phones may cache them for good.
  const immutable = rel.startsWith("assets/");
  entries.push(
    `  ${JSON.stringify(name)}: { type: ${JSON.stringify(types[ext])}, binary: ${binary}, immutable: ${immutable}, body: ${JSON.stringify(body)} },`,
  );
}

const out = `// Generated by scripts/embed-web.mjs from web/dist. Do not edit by hand.
export const webAssets: Record<string, { type: string; binary: boolean; immutable: boolean; body: string }> = {
${entries.join("\n")}
};
`;
writeFileSync(new URL("../agent/lib/web-assets.ts", import.meta.url), out);
console.log(`embedded ${entries.length} web assets`);
